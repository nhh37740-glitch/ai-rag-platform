    def set_user_active(self, ctx: RequestContext, user_id: str, active: bool) -> None: ...
    def reserve_site_quota(self, ctx: RequestContext, local_date: str, limit: int) -> Optional[int]: ...
    def site_quota_used(self, ctx: RequestContext, local_date: str) -> int: ...
    def create_notebook(self, ctx: RequestContext, metadata: dict) -> dict: ...
    def get_notebook(self, ctx: RequestContext, notebook_id: str) -> Optional[dict]: ...
    def list_notebooks(self, ctx: RequestContext, user_id: str) -> list[dict]: ...
    def update_notebook(self, ctx: RequestContext, notebook_id: str, name: str) -> None: ...
    def delete_document(self, ctx: RequestContext, notebook_id: str, source_id: str) -> None: ...
    def delete_notebook(self, ctx: RequestContext, notebook_id: str) -> None: ...
    def membership_snapshot(self, ctx: RequestContext, notebook_id: str) -> dict: ...
