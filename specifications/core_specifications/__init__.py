    def put_member(self, ctx: RequestContext, notebook_id: str, user_id: str, role: str) -> None: ...
    def delete_member(self, ctx: RequestContext, notebook_id: str, user_id: str) -> None: ...
    def list_conversations(self, ctx: RequestContext, user_id: str, notebook_id: Optional[str] = None) -> list[dict]: ...
